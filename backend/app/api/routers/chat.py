import re
from pathlib import Path

from fastapi import APIRouter, HTTPException

from app.core.database import get_repository_metadata
from app.models.schemas import ChatRequest, ChatResponse, SourceEvidence
from app.services.ollama_service import build_system_prompt, check_ollama_status, query_ollama_chat
from app.services.repo_service import read_repo_file
from app.services.search_service import search_repository

router = APIRouter(prefix="/chat", tags=["AI Repository Assistant"])


@router.post("", response_model=ChatResponse)
async def chat_with_repository(req: ChatRequest):
    repo = get_repository_metadata(req.repository_id)
    if not repo:
        raise HTTPException(status_code=404, detail="Repository not found.")
    repo_dir = Path(repo["path"])

    evidence: list[SourceEvidence] = []
    related_files: list[str] = []

    # 1. If user has a currently selected file, prioritize its context
    if req.selected_file:
        s_file = req.selected_file.replace("\\", "/").strip("/")
        try:
            content, _, line_count = read_repo_file(repo_dir, s_file)
            lines = content.splitlines()
            s_line = req.selected_lines[0] if req.selected_lines and len(req.selected_lines) > 0 else 1
            e_line = req.selected_lines[-1] if req.selected_lines and len(req.selected_lines) > 1 else min(line_count, 35)

            snippet = "\n".join(lines[max(0, s_line - 1):min(len(lines), e_line)])
            evidence.append(SourceEvidence(
                file_path=s_file,
                start_line=s_line,
                end_line=e_line,
                snippet=snippet,
                relevance_reason="Active file in Code Explorer"
            ))
            related_files.append(s_file)
        except Exception:
            pass

    # 2. Extract search terms from user question
    query_tokens = re.findall(r"[A-Za-z_][A-Za-z0-9_]{2,}", req.message)
    stop_words = {"how", "what", "where", "why", "when", "which", "does", "this", "that", "code", "file", "project"}
    filtered_tokens = [t for t in query_tokens if t.lower() not in stop_words]

    for token in filtered_tokens[:4]:
        search_res = search_repository(repo_dir, token, limit=3)
        for item in search_res.results:
            if any(e.file_path == item.file_path and abs(e.start_line - item.line_number) < 5 for e in evidence):
                continue

            content, _, line_count = read_repo_file(repo_dir, item.file_path)
            lines = content.splitlines()
            s_line = max(1, item.line_number - 2)
            e_line = min(line_count, item.line_number + 3)
            snippet = "\n".join(lines[s_line - 1:e_line])

            evidence.append(SourceEvidence(
                file_path=item.file_path,
                start_line=s_line,
                end_line=e_line,
                snippet=snippet,
                relevance_reason=f"Matched term '{token}' at line {item.line_number}"
            ))
            if item.file_path not in related_files:
                related_files.append(item.file_path)

            if len(evidence) >= 5:
                break
        if len(evidence) >= 5:
            break

    # 3. Check Ollama model status
    ollama_status = await check_ollama_status()

    if ollama_status.running and not ollama_status.error:
        system_prompt = build_system_prompt(evidence)
        conv_hist = [{"role": m.role, "content": m.content} for m in req.conversation_history[-6:]]
        success, answer, err = await query_ollama_chat(system_prompt, req.message, conv_hist)

        if success:
            sufficiency = "High" if len(evidence) >= 2 else "Partial"
            return ChatResponse(
                answer=answer,
                evidence=evidence,
                confidence_assessment=f"Grounding evidence sufficiency: {sufficiency}. Inferred by {ollama_status.model}.",
                related_files=related_files,
                limitations="Responses are generated by an open-weight local model bounded by retrieved source snippets."
            )

    # 4. Fallback when Ollama is offline or model missing
    # Honest evidence-grounded summary without pretending AI generated it
    evidence_summary = ""
    for ev in evidence:
        evidence_summary += f"\n- **{ev.file_path}** (lines {ev.start_line}-{ev.end_line}): `{ev.relevance_reason}`\n"

    status_warning = (
        f"> **Model Status**: Ollama inference is currently offline ({ollama_status.setup_instructions or 'Ollama not detected'}).\n\n"
    )

    fallback_answer = (
        f"{status_warning}"
        f"### Retrieved Source Evidence for: *\"{req.message}\"*\n\n"
        f"RepoPilot AI indexed the active repository and located relevant code locations based on your query:\n"
        f"{evidence_summary if evidence_summary else 'No exact keyword matches found in current repository files.'}\n\n"
        "To enable real-time generative reasoning, start Ollama with `ollama serve` and pull `qwen2.5-coder:7b`."
    )

    return ChatResponse(
        answer=fallback_answer,
        evidence=evidence,
        confidence_assessment="Local Source Retrieval (Ollama runtime offline)",
        related_files=related_files,
        limitations="Offline retrieval fallback mode: Shows exact matching source locations without generative completion."
    )
